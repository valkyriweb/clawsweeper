#!/usr/bin/env node
// Derive the guard constants of PrAutomergeGate.tla from the real code, then
// print a TLC config. A code change that removes a guard flips its constant,
// and TLC then shows what that change lets happen.
//
// Requires dist/ from: pnpm run build:repair
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const { buildAutomergeMergeArgs, reviewedHeadShaBlockReason } = await import(
  path.join(root, "dist/repair/comment-router-core.js")
);
const routerSource = fs.readFileSync(path.join(root, "src/repair/comment-router.ts"), "utf8");

const reviewed = "a".repeat(40);
const moved = "b".repeat(40);

// gh pr merge must carry --match-head-commit <reviewed head>.
const mergeArgs = buildAutomergeMergeArgs({
  issueNumber: 1,
  repo: "owner/repo",
  expectedHeadSha: reviewed,
});
const matchAt = mergeArgs.indexOf("--match-head-commit");
const matchHeadOnMerge = matchAt >= 0 && mergeArgs[matchAt + 1] === reviewed;

// The router refuses a pass marker whose SHA is not the live head, both when it
// classifies the pass and again in validateAutomergeReadiness.
const staleBlocked =
  reviewedHeadShaBlockReason({
    expectedHeadSha: reviewed,
    currentHeadSha: moved,
    markerName: "pass",
  }) !== null &&
  reviewedHeadShaBlockReason({
    expectedHeadSha: reviewed,
    currentHeadSha: reviewed,
    markerName: "pass",
  }) === null;
const classify = functionBody(routerSource, "function classifyAutomergePass(");
const readiness = functionBody(routerSource, "function validateAutomergeReadiness(");
const staleHeadBlocks =
  staleBlocked &&
  /reviewedHeadShaBlockReason\(\{[\s\S]*?currentHeadSha:\s*command\.target\?\.head_sha/.test(
    classify,
  ) &&
  /reviewedHeadShaBlockReason\(\{[\s\S]*?currentHeadSha:\s*view\.headRefOid/.test(readiness);

// Does the merge path re-read the ClawSweeper verdict after it took the pass?
// Today neither function reads comments or verdict markers. If a change adds a
// verdict re-read here, this flips to TRUE; confirm it by reading the code.
const execute = functionBody(routerSource, "function executeAutomerge(");
const recheckVerdictBeforeMerge =
  /hasTrustedPassForHead|clawsweeper-verdict|issueCommentsFor\([^)]*\)[\s\S]*?verdict/.test(
    readiness,
  ) || /hasTrustedPassForHead|clawsweeper-verdict/.test(execute);

const tla = (value) => (value ? "TRUE" : "FALSE");
const guards = {
  StaleHeadBlocks: staleHeadBlocks,
  MatchHeadOnMerge: matchHeadOnMerge,
  RecheckVerdictBeforeMerge: recheckVerdictBeforeMerge,
};
for (const [name, value] of Object.entries(guards)) {
  process.stderr.write(`guard ${name} = ${tla(value)}\n`);
}
process.stdout.write(
  [
    "\\* Generated by derive-guards.mjs from the code. Do not edit.",
    "SPECIFICATION Spec",
    "CONSTANTS",
    "    MaxHead = 2",
    ...Object.entries(guards).map(([name, value]) => `    ${name} = ${tla(value)}`),
    "INVARIANTS",
    "    TypeOK",
    "    MergedCommitWasReviewed",
    "    NoMergeOverFailVerdict",
    "",
  ].join("\n"),
);

function functionBody(source, signature) {
  const start = source.indexOf(signature);
  if (start < 0)
    throw new Error(`derive-guards: ${signature} not found; update the model coverage`);
  const open = source.indexOf("{\n", start);
  let depth = 0;
  for (let index = open; index < source.length; index++) {
    if (source[index] === "{") depth++;
    else if (source[index] === "}" && --depth === 0) return source.slice(start, index + 1);
  }
  throw new Error(`derive-guards: unbalanced body for ${signature}`);
}
